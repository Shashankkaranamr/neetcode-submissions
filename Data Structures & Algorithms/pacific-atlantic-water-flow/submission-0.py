class Solution:
    

    def pacificAtlantic(self, heights: List[List[int]]) -> List[List[int]]:
        def dfs(queue,grid):
            while queue:
                r,c=queue.popleft()
                grid[r][c]=1
                for dr,dc in directions:
                    nr,nc=r+dr,c+dc
                    if 0<=nr<m and 0<=nc<n and heights[nr][nc]>=heights[r][c] and grid[nr][nc]!=1:
                        queue.append((nr,nc))

        m,n=len(heights),len(heights[0])
        pacific_grid = [[1 if r == 0 or c == 0 else 0 for c in range(n)] for r in range(m)]
        atlantic_grid = [[1 if r == m-1 or c == n-1 else 0 for c in range(n)] for r in range(m)]
        pacific_queue=deque()
        atlantic_queue=deque()
        queue=deque()
        directions=[(0,1),(0,-1),(1,0),(-1,0)]
        for i in range(m):
            for j in range(n):
                if pacific_grid[i][j]==1:
                    pacific_queue.append((i,j))
                if atlantic_grid[i][j]==1:
                    atlantic_queue.append((i,j))
        dfs(pacific_queue,pacific_grid)
        dfs(atlantic_queue,atlantic_grid)
        result=[]
        for i in range(m):
            for j in range(n):
                if pacific_grid[i][j]==1 and atlantic_grid[i][j]==1:
                    result.append([i,j])
        return result
        
        
        










































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































        